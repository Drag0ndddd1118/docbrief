"""Markdown export of an analysis (+ optional Q&A transcript)."""
from __future__ import annotations

from .types import Analysis


def _pg(p) -> str:
    return f" _(p.{p})_" if p else ""


def to_markdown(a: Analysis, qa: list[dict] | None = None) -> str:
    L = [f"# {a.title}", "", f"**Type:** {a.doc_type.replace('_', ' ')}  ·  **Generated by:** {a.engine}", ""]
    if a.tldr:
        L += [f"> {a.tldr}", ""]
    L += ["## Summary", "", a.summary, "", "## Key points", ""]
    L += [f"- {p.text}{_pg(p.page)}" for p in a.key_points]
    if a.metrics:
        L += ["", "## Key metrics", "", "| Metric | Value | Period | Page | Verified in PDF |", "|---|---|---|---|---|"]
        for m in a.metrics:
            v = {True: "yes", False: "NOT FOUND — check", None: "-"}[m.verified]
            L.append(f"| {m.name} | {m.value} | {m.period} | {m.page or ''} | {v} |")
    if a.risks:
        L += ["", "## Risks / limitations", ""] + [f"- {p.text}{_pg(p.page)}" for p in a.risks]
    if qa:
        L += ["", "## Q&A", ""]
        for t in qa:
            L += [f"**{'Q' if t['role'] == 'user' else 'A'}:** {t['content']}", ""]
    return "\n".join(L) + "\n"

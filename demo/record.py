import json, time, shutil, glob, os
from playwright.sync_api import sync_playwright
OUT = "/workspace/nebius-hack/demo/build"
for f in glob.glob(OUT + "/raw/*"): os.remove(f)
marks = {}
def mark(n): marks[n] = round(time.time() - T0, 2); print(n, marks[n], flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox", "--hide-scrollbars"])
    ctx = b.new_context(viewport={"width": 1440, "height": 810}, record_video_dir=OUT + "/raw", record_video_size={"width": 1440, "height": 810})
    pg = ctx.new_page(); T0 = time.time()
    pg.goto("http://127.0.0.1:8612"); pg.wait_for_selector("text=DocBrief", timeout=30000)
    pg.wait_for_timeout(2500); mark("home")
    pg.wait_for_timeout(2500)
    pg.set_input_files("input[type=file]", "/workspace/nebius-hack/samples/aurora_robotics_fy2025_report.pdf"); mark("upload")
    pg.wait_for_selector("text=Key metrics", timeout=180000); mark("analysis_done")
    pg.wait_for_timeout(5500); mark("summary_end")
    pg.get_by_text("Key points").first.click(); pg.wait_for_timeout(4500); mark("points_end")
    pg.get_by_text("Key metrics").first.click(); pg.wait_for_timeout(3000); mark("metrics_show")
    pg.mouse.wheel(0, 250); pg.wait_for_timeout(6500); mark("metrics_end")
    pg.get_by_text("Fact-check with the web").first.click(); pg.wait_for_timeout(2500); mark("web_open")
    pg.get_by_role("button", name="Fact-check key claims").click(); mark("web_click")
    pg.wait_for_selector("text=reconciliation", timeout=180000); pg.wait_for_timeout(800); mark("web_done")
    pg.mouse.wheel(0, 220); pg.wait_for_timeout(1500); pg.screenshot(path=OUT + "/web1.png"); pg.wait_for_timeout(5500); mark("web_read1")
    pg.mouse.wheel(0, 350); pg.wait_for_timeout(1200); pg.screenshot(path=OUT + "/web2.png"); pg.wait_for_timeout(5500); mark("web_read2")
    pg.mouse.wheel(0, -2000); pg.wait_for_timeout(500)
    pg.get_by_text("Ask the document").first.click(); pg.wait_for_timeout(2500); mark("ask_open")
    box = pg.get_by_placeholder("Ask anything about this document", exact=False)
    box.click(); box.press_sequentially("What is the revenue guidance for fiscal 2026?", delay=55); pg.wait_for_timeout(600); mark("q1_typed")
    box.press("Enter"); mark("q1_sent")
    pg.wait_for_function("document.body.innerText.includes('[p.4]')", timeout=120000); mark("q1_answer")
    pg.wait_for_timeout(5500); mark("q1_read")
    pg.get_by_text("Sources (").first.click(); pg.wait_for_timeout(500); mark("src_open"); pg.mouse.wheel(0, 200); pg.wait_for_timeout(4500); mark("src_end")
    pg.get_by_text("Sources (").first.click(); pg.wait_for_timeout(600); pg.mouse.wheel(0, -2000); pg.wait_for_timeout(600); mark("src_closed")
    box = pg.get_by_placeholder("Ask anything about this document", exact=False)
    box.click(); box.press_sequentially("公司的主要风险是什么？", delay=120); pg.wait_for_timeout(600); mark("q2_typed")
    n0 = pg.locator("[data-testid=stChatMessage]").count()
    box.press("Enter"); mark("q2_sent")
    pg.wait_for_function("(n)=>{const m=document.querySelectorAll('[data-testid=stChatMessage]');return m.length>=n+2 && /[\\u4e00-\\u9fff]{20}/.test(m[m.length-1].innerText)}", arg=n0, timeout=150000); mark("q2_answer")
    pg.wait_for_timeout(800); pg.locator("[data-testid=stChatMessage]").last.scroll_into_view_if_needed(); pg.mouse.wheel(0, 150); pg.wait_for_timeout(1200); mark("q2_shown"); pg.screenshot(path=OUT + "/q2.png"); pg.wait_for_timeout(5500); mark("q2_read")
    pg.locator("section[data-testid=stSidebar] label", has_text="Deep reasoning").first.click(); pg.wait_for_timeout(2500); mark("deep")
    pg.screenshot(path=OUT + "/end.png"); pg.wait_for_timeout(1500); mark("end")
    json.dump(marks, open(OUT + "/marks.json", "w"), indent=1)
    ctx.close(); b.close()
for f in glob.glob(OUT + "/raw/*.webm"): shutil.move(f, OUT + "/raw.webm")

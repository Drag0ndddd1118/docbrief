import json, time, shutil, glob, os
from playwright.sync_api import sync_playwright
OUT = "/workspace/nebius-hack/demo/build"
os.makedirs(OUT, exist_ok=True)
for f in glob.glob(OUT + "/raw/*"): os.remove(f)
marks = {}
def mark(n): marks[n] = round(time.time() - T0, 2); print(n, marks[n], flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox", "--hide-scrollbars"])
    ctx = b.new_context(viewport={"width": 1440, "height": 810}, record_video_dir=OUT + "/raw", record_video_size={"width": 1440, "height": 810})
    pg = ctx.new_page(); T0 = time.time()
    pg.goto("http://127.0.0.1:8612"); pg.wait_for_selector("text=Ask any 10-K", timeout=30000)
    pg.mouse.move(900, 450); pg.wait_for_timeout(3000); mark("home")
    pg.mouse.wheel(0, 330); pg.wait_for_timeout(4500); mark("home_cards")
    pg.get_by_role("button", name="Try the preloaded").click(); mark("click_show")
    pg.wait_for_selector("text=TL;DR", timeout=30000); pg.wait_for_timeout(5000); mark("show_loaded")
    pg.get_by_text("Key metrics").first.click(); pg.wait_for_selector("text=found in PDF"); pg.wait_for_timeout(1500); mark("metrics")
    pg.wait_for_timeout(5500); mark("metrics_end")
    pg.get_by_text("Fact-check with the web").first.click(); pg.wait_for_selector("text=reconciliation", timeout=20000); pg.wait_for_timeout(1500); mark("fc_cached")
    pg.mouse.wheel(0, 260); pg.wait_for_timeout(5500); mark("fc_cached_end")
    pg.mouse.wheel(0, -600); pg.wait_for_timeout(800)
    pg.get_by_role("button", name="Re-run live with Tavily").click(); mark("fc_click")
    pg.wait_for_function("!document.body.innerText.includes('pre-computed with the live pipeline')", timeout=150000); mark("fc_running")
    pg.wait_for_function("document.body.innerText.includes('pre-computed with the live pipeline')===false && document.querySelectorAll('.db-fc').length>=1", timeout=180000); pg.wait_for_timeout(1000); mark("fc_live_done")
    pg.mouse.wheel(0, 260); pg.wait_for_timeout(5500); mark("fc_live_end")
    pg.mouse.wheel(0, -900); pg.wait_for_timeout(500)
    pg.get_by_text("Ask the document").first.click(); pg.wait_for_timeout(2500); mark("ask_open")
    pg.get_by_role("button", name="Who are NVIDIA").click(); pg.wait_for_selector("text=pre-computed by Nemotron", timeout=20000); pg.wait_for_timeout(500); mark("ans1")
    pg.wait_for_timeout(5500); mark("ans1_read")
    pg.get_by_text("Sources (").first.click(); pg.wait_for_timeout(500); mark("src_open"); pg.mouse.wheel(0, 260); pg.wait_for_timeout(4500); mark("src_end")
    pg.get_by_text("Sources (").first.click(); pg.wait_for_timeout(500); pg.mouse.wheel(0, -2000); pg.wait_for_timeout(500)
    box = pg.get_by_placeholder("Ask the NVIDIA 10-K", exact=False)
    q = "What did NVIDIA say about H20 export licenses for China?"
    box.click(); box.press_sequentially(q, delay=45); pg.wait_for_timeout(500); mark("q2_typed")
    n0 = pg.locator("[data-testid=stChatMessage]").count()
    box.press("Enter"); mark("q2_sent"); pg.wait_for_timeout(1200)
    pg.wait_for_function("(n)=>{const m=document.querySelectorAll('[data-testid=stChatMessage]');return m.length>=n+2 && !document.querySelector('[data-testid=stSpinner]') && /\\[p\\.\\d/.test(m[m.length-1].innerText)}", arg=n0, timeout=150000); mark("q2_answer")
    pg.wait_for_timeout(500); pg.locator("[data-testid=stChatMessage]").last.scroll_into_view_if_needed(); pg.wait_for_timeout(6500); mark("q2_read")
    pg.screenshot(path=OUT + "/q2.png")
    box = pg.get_by_placeholder("Ask the NVIDIA 10-K", exact=False)
    box.click(); box.press_sequentially("英伟达2026财年的营收和毛利率是多少，同比变化如何？", delay=110); pg.wait_for_timeout(500); mark("q3_typed")
    n0 = pg.locator("[data-testid=stChatMessage]").count()
    box.press("Enter"); mark("q3_sent")
    pg.wait_for_function("(n)=>{const m=document.querySelectorAll('[data-testid=stChatMessage]');return m.length>=n+2 && /[\\u4e00-\\u9fff]{8}/.test(m[m.length-1].innerText)}", arg=n0, timeout=60000); mark("q3_answer")
    pg.wait_for_timeout(500); pg.locator("[data-testid=stChatMessage]").last.scroll_into_view_if_needed(); pg.wait_for_timeout(5500); mark("q3_read")
    pg.mouse.move(900, 450); pg.mouse.wheel(0, -3000); pg.wait_for_timeout(500)
    sb = pg.locator("section[data-testid=stSidebar]"); sb.hover(); pg.mouse.wheel(0, 500); pg.wait_for_timeout(5500); mark("meter")
    pg.screenshot(path=OUT + "/meter.png")
    json.dump(marks, open(OUT + "/marks3.json", "w"), indent=1)
    ctx.close(); b.close()
for f in glob.glob(OUT + "/raw/*.webm"): shutil.move(f, OUT + "/raw3.webm")
